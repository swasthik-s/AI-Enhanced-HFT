-- Run this once in Supabase Dashboard -> SQL Editor.
create table if not exists public.telemetry (
  id bigint generated by default as identity primary key,
  received_at timestamptz not null default now(),
  account_login text,
  server text,
  symbol text,
  timeframe text,
  payload jsonb not null
);

create index if not exists telemetry_received_at_idx
  on public.telemetry (received_at desc);
create index if not exists telemetry_symbol_received_at_idx
  on public.telemetry (symbol, received_at desc);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  received_at timestamptz not null default now(),
  severity text not null default 'INFO',
  event_type text not null,
  message text not null,
  payload jsonb not null default '{}'::jsonb
);

create index if not exists events_received_at_idx
  on public.events (received_at desc);

-- Keep direct client access disabled. The API uses a server-side Supabase secret key.
alter table public.telemetry enable row level security;
alter table public.events enable row level security;
